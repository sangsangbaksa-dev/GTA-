using Harbor.Core.Data;
using Harbor.Core.Geometry;
using Harbor.Core.Math;

namespace Harbor.Core.World;

/// <summary>Collision footprint and gameplay tag of one placeable asset (data/world/assets.json).
/// Min/Size are the asset's local AABB at rotation 0, measured from the imported .glb.</summary>
public sealed record AssetDef
{
    public double[] Min { get; init; } = new double[3];
    public double[] Size { get; init; } = new double[3];
    public SurfaceMaterial Material { get; init; } = SurfaceMaterial.Concrete;
    public string Tag { get; init; } = "";
    /// <summary>False for decoration the server ignores (cones, lamps' light radius...).</summary>
    public bool Solid { get; init; } = true;
}

/// <summary>One asset instance. Rot = quarter turns around +Y (counter-clockwise from above, same as Godot rotation.y).</summary>
public sealed record Placement(string Asset, double[] Pos, int Rot = 0);

public sealed record RoadDef(double[] From, double[] To, double Width = 10);

/// <summary>Named area used for labels/HUD (district boundaries are rectangles [minX, minZ, maxX, maxZ]).</summary>
public sealed record AreaDef(string Id, string District, double[] Rect);

/// <summary>The playable city layout shared by the authoritative server (collision) and Godot (visuals) — ADR 0008.
/// Generated by tools/map/build_map.py; never hand-placed in .tscn so both sides always agree.</summary>
public sealed record MapData
{
    public double[] Bounds { get; init; } = { -1000, -1000, 1000, 1000 };
    public double[] Spawn { get; init; } = { 0, 0, 0 };
    public List<RoadDef> Roads { get; init; } = new();
    public List<AreaDef> Areas { get; init; } = new();
    public List<Placement> Placements { get; init; } = new();
    public Dictionary<string, AssetDef> Assets { get; init; } = new();

    public static readonly MapData Empty = new() { Bounds = new double[] { -100, -100, 100, 100 } };

    public Vec3d SpawnPoint => new(Spawn[0], Spawn[1], Spawn[2]);

    public void Validate()
    {
        Json.Require(Bounds.Length == 4 && Bounds[2] > Bounds[0] && Bounds[3] > Bounds[1], "map.bounds must be [minX,minZ,maxX,maxZ]");
        foreach (var p in Placements)
        {
            Json.Require(Assets.ContainsKey(p.Asset), $"map: unknown asset {p.Asset}");
            Json.Require(p.Pos.Length == 3 && p.Rot is >= 0 and < 4, $"map: bad placement of {p.Asset}");
        }
        foreach (var (id, a) in Assets)
            Json.Require(a.Min.Length == 3 && a.Size.Length == 3 && a.Size.All(s => s >= 0), $"asset {id}: min/size must have 3 numbers");
    }

    /// <summary>World AABB of a placement (asset AABB rotated by quarter turns, then translated).</summary>
    public Aabb BoundsOf(Placement p)
    {
        var a = Assets[p.Asset];
        var min = new Vec3d(a.Min[0], a.Min[1], a.Min[2]);
        var max = min + new Vec3d(a.Size[0], a.Size[1], a.Size[2]);
        Vec3d R(Vec3d v) => (p.Rot & 3) switch
        {
            // rotation about +Y by k*90°: x' = x cos + z sin, z' = -x sin + z cos
            1 => new Vec3d(v.Z, v.Y, -v.X),
            2 => new Vec3d(-v.X, v.Y, -v.Z),
            3 => new Vec3d(-v.Z, v.Y, v.X),
            _ => v,
        };
        var c1 = R(min);
        var c2 = R(max);
        var lo = new Vec3d(System.Math.Min(c1.X, c2.X), System.Math.Min(c1.Y, c2.Y), System.Math.Min(c1.Z, c2.Z));
        var hi = new Vec3d(System.Math.Max(c1.X, c2.X), System.Math.Max(c1.Y, c2.Y), System.Math.Max(c1.Z, c2.Z));
        var t = new Vec3d(p.Pos[0], p.Pos[1], p.Pos[2]);
        return new Aabb(lo + t, hi + t);
    }

    /// <summary>Fills server collision from solid placements. Returns the created box id per placement index.</summary>
    public Dictionary<int, int> BuildStatic(StaticWorld world)
    {
        var ids = new Dictionary<int, int>();
        for (var i = 0; i < Placements.Count; i++)
        {
            var p = Placements[i];
            var a = Assets[p.Asset];
            if (!a.Solid) continue;
            ids[i] = world.Add(BoundsOf(p), a.Material, a.Tag);
        }
        return ids;
    }

    public AreaDef? AreaAt(Vec3d pos) =>
        Areas.FirstOrDefault(a => pos.X >= a.Rect[0] && pos.Z >= a.Rect[1] && pos.X <= a.Rect[2] && pos.Z <= a.Rect[3]);
}
