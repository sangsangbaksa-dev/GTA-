using Harbor.Core.Data;
using Harbor.Core.Math;

namespace Harbor.Core.Agents;

/// <summary>How a faction treats players: always hostile, or only while the player is wanted (police).</summary>
public enum PlayerStance { Always, Wanted, Never }

/// <summary>Combat behaviour family (ARCHITECTURE §3.5): charge = melee rush, cover = cover/flank gunfighter,
/// advance = slow armoured push (shield).</summary>
public enum AgentStyle { Charge, Cover, Advance }

public sealed record FactionDef
{
    public string Id { get; init; } = "";
    public string DisplayName { get; init; } = "";
    /// <summary>Combat team id. Negative so it never collides with player crew ids (no friendly fire inside a faction).</summary>
    public int Team { get; init; }
    public PlayerStance Players { get; init; } = PlayerStance.Always;
    public List<string> Enemies { get; init; } = new();
    /// <summary>Heat crime reported when a player kills a member (data/ai/heat.json).</summary>
    public string KillCrime { get; init; } = "";
}

public sealed record ArchetypeDef
{
    public string Id { get; init; } = "";
    public string Faction { get; init; } = "";
    /// <summary>Character asset (game/assets/characters/*.glb) — presentation only, replicated to clients.</summary>
    public string Model { get; init; } = "";
    public AgentStyle Style { get; init; }
    public int Health { get; init; } = 100;
    public int Armor { get; init; }
    /// <summary>Weapon id (data/weapons) or empty for melee-only.</summary>
    public string Weapon { get; init; } = "";
    public double SpeedMultiplier { get; init; } = 1.0;
    public double SightRange { get; init; } = 50;
    public double FovDeg { get; init; } = 120;
    public double ReactionSeconds { get; init; } = 0.6;
    public double AttackRange { get; init; } = 30;
    public double PreferredRange { get; init; } = 15;
    public double AimErrorDeg { get; init; } = 3;
    public double BurstSeconds { get; init; } = 0.8;
    public double BurstPauseSeconds { get; init; } = 1.0;
    public double MeleeDamage { get; init; }
    public double MeleeRange { get; init; } = 1.7;
    public double MeleeCooldown { get; init; } = 1.0;
    /// <summary>Damage multiplier for hits arriving inside the front cone (riot shield). 1 = no shield.</summary>
    public double ShieldFrontScale { get; init; } = 1.0;
    public double ShieldConeDeg { get; init; } = 70;
    /// <summary>[min, max] dirty cash dropped when a player kills this NPC.</summary>
    public List<long> CashDrop { get; init; } = new() { 0, 0 };
}

public sealed record EncounterMember(string Archetype, int Count = 1);

/// <summary>A group of NPCs guarding a place (gang turf, Ironclad post). Spawns when a player comes near,
/// respawns after being wiped out (data/ai/encounters.json, generated by tools/map/build_map.py).</summary>
public sealed record EncounterDef
{
    public string Id { get; init; } = "";
    public double[] Position { get; init; } = new double[3];
    public double Radius { get; init; } = 8;
    public double LeashRadius { get; init; } = 60;
    public double RespawnSeconds { get; init; } = 180;
    public List<EncounterMember> Members { get; init; } = new();

    public Vec3d Center => new(Position[0], Position[1], Position[2]);
}

public sealed record PoliceConfig
{
    public int MaxUnitsPerPlayer { get; init; } = 10;
    public int MaxUnitsTotal { get; init; } = 32;
    public double[] SpawnDistance { get; init; } = { 55, 85 };
    public int SpawnBatch { get; init; } = 2;
    public int SwatFromLevel { get; init; } = 4;
    public double DespawnAfterSeconds { get; init; } = 20;
    public string Officer { get; init; } = "police_officer";
    public string Swat { get; init; } = "police_swat";
}

/// <summary>Everything under data/ai/ except heat.json.</summary>
public sealed record AgentData
{
    public Dictionary<string, FactionDef> Factions { get; init; } = new();
    public Dictionary<string, ArchetypeDef> Archetypes { get; init; } = new();
    public List<EncounterDef> Encounters { get; init; } = new();
    public PoliceConfig Police { get; init; } = new();
    public double CorpseSeconds { get; init; } = 12;
    public double ThinkHz { get; init; } = 10;
    /// <summary>Encounters spawn when any player is this close, and despawn when none is within the deactivation radius.</summary>
    public double ActivationRadius { get; init; } = 220;
    public double DeactivationRadius { get; init; } = 320;

    public static readonly AgentData Empty = new();

    public void Validate(ICollection<string> weaponIds, ICollection<string> crimes)
    {
        foreach (var f in Factions.Values)
        {
            Json.Require(f.Team < 0, $"faction {f.Id}: team must be negative");
            Json.Require(f.KillCrime.Length == 0 || crimes.Contains(f.KillCrime), $"faction {f.Id}: unknown crime {f.KillCrime}");
            foreach (var e in f.Enemies) Json.Require(Factions.ContainsKey(e), $"faction {f.Id}: unknown enemy {e}");
        }
        Json.Require(Factions.Values.Select(f => f.Team).Distinct().Count() == Factions.Count, "faction teams must be unique");
        foreach (var a in Archetypes.Values)
        {
            Json.Require(Factions.ContainsKey(a.Faction), $"archetype {a.Id}: unknown faction {a.Faction}");
            Json.Require(a.Weapon.Length == 0 || weaponIds.Contains(a.Weapon), $"archetype {a.Id}: unknown weapon {a.Weapon}");
            Json.Require(a.Weapon.Length > 0 || a.MeleeDamage > 0, $"archetype {a.Id}: needs a weapon or melee damage");
            Json.Require(a.Health > 0 && a.ShieldFrontScale is >= 0 and <= 1, $"archetype {a.Id}: bad health/shield");
            Json.Require(a.CashDrop.Count == 2 && a.CashDrop[0] >= 0 && a.CashDrop[1] >= a.CashDrop[0], $"archetype {a.Id}: cashDrop must be [min,max]");
        }
        foreach (var e in Encounters)
        {
            Json.Require(e.Position.Length == 3, $"encounter {e.Id}: position must have 3 numbers");
            foreach (var m in e.Members) Json.Require(Archetypes.ContainsKey(m.Archetype), $"encounter {e.Id}: unknown archetype {m.Archetype}");
        }
        Json.Require(Encounters.Select(e => e.Id).Distinct().Count() == Encounters.Count, "duplicate encounter id");
        if (Archetypes.Count > 0)
        {
            Json.Require(Archetypes.ContainsKey(Police.Officer) && Archetypes.ContainsKey(Police.Swat), "police archetypes missing");
            Json.Require(Police.SpawnDistance.Length == 2 && Police.SpawnDistance[0] > 0 && Police.SpawnDistance[1] >= Police.SpawnDistance[0], "police.spawnDistance must be [min,max]");
        }
    }
}
